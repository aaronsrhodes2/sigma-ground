-- world/constants.lua -- the construct's physics, as pure logic over the generated table (constants_data.lua).
--
-- PURE Lua 5.1 / LuaJIT: no GMod globals, so the same file runs in the game (both realms) and in the offline tests.
--
-- REAL-WORLD PHYSICS ONLY (Aaron, 2026-10-12).  Gravity is Earth's, from the sigma-ground library, unless a real place is asked
-- for (the Moon, Mars, Jupiter, free fall).  Air drag is the real F = 1/2 rho Cd A v^2 per object (see world/aero.lua).  There is
-- no gameplay multiplier and no universal damping number.  The numbers are NOT typed here: constants_data.lua is generated by
-- stage/gmod/holodeck/world_constants.py from the library, each entry with units, source and status.
--
-- State (what a server keeps, in archived convars):
--   preset           the gravity in force: "earth" (default) | "moon" | "mars" | "jupiter" | "zero"
--   engine_air_drag  true = leave Source's own air drag on too (a measurement switch; default false)
--   time_scale       phys_timescale multiplier (1 = untouched)
local M = {}

local inc = include or function(p) return dofile(p) end
local data = inc("mentat/world/constants_data.lua")
M.data = data

local abs, max = math.abs, math.max

M.HU_M = data.hu_m
M.ENGINE_GRAVITY_HU_S2 = data.engine_gravity_hu_s2
M.LIMITS = data.limits
M.PRESETS = data.presets
M.PRESET_ORDER = { "earth", "moon", "mars", "jupiter", "zero" }
M.AIR_DENSITY = data.entries.air_density.value          -- kg/m^3, from the library
M.CD = data.cd

M.DEFAULTS = {
  preset = data.default_preset,
  engine_air_drag = data.entries.engine_air_drag.value,
  time_scale = data.entries.time_scale.value,
}

local function finite(n) return type(n) == "number" and n == n and n > -math.huge and n < math.huge end

--- Every entry must carry value, units, source and status (the contract the docs promise).
function M.validate_data(d)
  d = d or data
  local function entry_ok(name, e)
    if type(e) ~= "table" then return false, name .. " is not a table" end
    if type(e.units) ~= "string" then return false, name .. " has no units" end
    for _, k in ipairs({ "source", "status" }) do
      if type(e[k]) ~= "string" or e[k] == "" then return false, name .. " has no " .. k end
    end
    if e.value == nil then return false, name .. " has no value" end
    return true
  end
  for _, group in ipairs({ "engine", "entries" }) do
    for name, e in pairs(d[group] or {}) do
      local ok, err = entry_ok(group .. "." .. name, e)
      if not ok then return false, err end
    end
  end
  for name, e in pairs(d.cd or {}) do
    if not finite(e.value) or e.value <= 0 or type(e.source) ~= "string" or e.source == "" or type(e.status) ~= "string" then
      return false, "cd." .. name .. " is incomplete"
    end
  end
  for name, p in pairs(d.presets or {}) do
    if not finite(p.gravity_m_s2) or p.gravity_m_s2 < 0 then return false, "preset " .. name .. " has no gravity" end
    if type(p.source) ~= "string" or p.source == "" or type(p.status) ~= "string" then return false, "preset " .. name .. " has no source" end
    if abs(p.gravity_hu_s2 * d.hu_m - p.gravity_m_s2) > 1e-9 * max(1, p.gravity_m_s2) then
      return false, "preset " .. name .. " HU/s^2 and m/s^2 disagree"
    end
  end
  return true
end

function M.clamp_time_scale(v)
  local lim = M.LIMITS.time_scale
  v = tonumber(v)
  if not finite(v) then return M.DEFAULTS.time_scale, true end
  if v < lim[1] then return lim[1], true end
  if v > lim[2] then return lim[2], true end
  return v, false
end

function M.new_state(over)
  local s = {}
  for k, v in pairs(M.DEFAULTS) do s[k] = v end
  for k, v in pairs(over or {}) do s[k] = v end
  if not M.PRESETS[s.preset] then s.preset = M.DEFAULTS.preset end
  s.time_scale = M.clamp_time_scale(s.time_scale)
  s.engine_air_drag = s.engine_air_drag and true or false
  return s
end

--- Everything the engine glue needs, from a state.
function M.derive(state)
  local p = M.PRESETS[state.preset]
  return {
    preset = state.preset,
    gravity_m_s2 = p.gravity_m_s2,
    gravity_hu_s2 = p.gravity_hu_s2,
    gravity_mult = p.gravity_mult,                    -- of the engine's own 600 HU/s^2 (about 0.86 for Earth)
    air_density = M.AIR_DENSITY,
    engine_air_drag = state.engine_air_drag,
    time_scale = state.time_scale,
  }
end

--- Apply one parsed intent (see world/intent.lua). Returns the new state and whether it was an intent this module resolves.
function M.resolve(state, it)
  local s = M.new_state(state)
  if it.kind == "gravity_preset" and M.PRESETS[it.name] then
    s.preset = it.name
    return s, true
  end
  return s, false
end

-- ------------------------------------------------------------------------------------------------ describing
local function g3(x)
  if x == 0 then return "0" end
  local s = string.format("%.3g", x)
  if s:find("e", 1, true) then s = string.format("%.4f", x) end
  return s
end
M.g3 = g3

--- One short sentence about the gravity in force (this is what Skippy says first).
function M.summary(state)
  local p = M.PRESETS[state.preset]
  local earth = M.PRESETS.earth
  local what = state.preset == "zero" and "Gravity is zero (free fall)"
    or ("Gravity is " .. (state.preset == "earth" and "Earth's" or (p.label .. "'s")) .. ", " .. g3(p.gravity_m_s2) .. " m/s2")
  return string.format("%s, %s HU/s2 here; the engine's own default is %s HU/s2. Air drag is real: 1/2 rho Cd A v squared per object, rho %s kg/m3.",
    what, g3(p.gravity_hu_s2), g3(data.engine_gravity_hu_s2), g3(M.AIR_DENSITY))
end

--- The table read back honestly: rows of { key, value (text), units, status, source }.
function M.rows(state)
  local d = M.derive(state)
  local p = M.PRESETS[state.preset]
  local E, N = data.entries, data.engine
  local rows = {}
  local function add(key, value, units, status, source) rows[#rows + 1] = { key = key, value = value, units = units, status = status, source = source } end
  add("gravity", g3(d.gravity_m_s2), "m/s2", p.status, p.source)
  add("gravity in engine units", g3(d.gravity_hu_s2), "HU/s2", "derived", "gravity / " .. g3(M.HU_M) .. " m per HU (the stage scale); engine default " .. g3(N.gravity_hu_s2.value) .. " HU/s2 is " .. g3(N.gravity_hu_s2.value / d.gravity_hu_s2) .. " x stronger than Earth's" )
  add("air density", g3(M.AIR_DENSITY), E.air_density.units, E.air_density.status, E.air_density.source)
  add("air drag", "F = 1/2 rho Cd A v^2", "", E.drag_law.status, E.drag_law.source)
  for _, k in ipairs({ "sphere", "box", "flat_plate", "cylinder" }) do
    local c = M.CD[k]
    add("Cd " .. k, g3(c.value), "", c.status, c.source)
  end
  add("engine air drag", state.engine_air_drag and "on" or "off", "", E.engine_air_drag.status, E.engine_air_drag.source)
  add("time scale", g3(state.time_scale), E.time_scale.units, state.time_scale == 1 and E.time_scale.status or "set by the server owner", E.time_scale.source)
  add("surfaces", "engine", "", N.surfaces.status, N.surfaces.source)
  add("players", "engine", "", N.players.status, N.players.source)
  return rows
end

--- The read-back as lines of at most 240 characters: the first is the spoken summary, the rest are private detail.
function M.readback(state)
  local lines = { M.summary(state) }
  local function put(s)
    while #s > 238 do
      local cut = s:sub(1, 238):match("^(.*)%s") or s:sub(1, 238)
      lines[#lines + 1] = cut
      s = s:sub(#cut + 1):gsub("^%s+", "")
    end
    if s ~= "" then lines[#lines + 1] = s end
  end
  for _, r in ipairs(M.rows(state)) do
    if r.key == "gravity" or r.key == "air density" or r.key == "air drag" or r.key == "Cd sphere" or r.key == "Cd box" or r.key == "engine air drag" or r.key == "surfaces" then
      put(r.key .. ": " .. r.value .. (r.units ~= "" and (" " .. r.units) or "") .. " [" .. r.status .. "] " .. r.source)
    end
  end
  lines[#lines + 1] = "The game models only gravity and aerodynamic drag here, and the engine's rigid bodies and friction. Thermodynamics, weather and fluids are not modelled."
  return lines
end

return M
