"""Build the Lua spec files the in-game framework loads: python stage/gmod/experiments/build.py [S01 ...]

Calls Mentat for every prediction (cached, see mentat_io.py), then writes
stage/gmod/addon/lua/mentat/exp_specs/<id>.lua and a JSON copy next to the cache for the grader.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import specs  # noqa: E402
from luaout import lua  # noqa: E402

LUA_DIR = HERE.parents[0] / "addon" / "lua" / "mentat" / "exp_specs"


def render(sid: str) -> str:
    """The text of the generated Lua spec for one experiment."""
    spec = specs.build(sid)
    header = (f"-- GENERATED by stage/gmod/experiments/build.py from Mentat's predictions: DO NOT EDIT BY HAND.\n"
              f"-- {sid} {spec['name']}   spec sha {spec['sha']}   (provenance for every number is in `provenance`)\n")
    return header + "return " + lua(spec) + "\n"


def write(sid: str) -> Path:
    LUA_DIR.mkdir(parents=True, exist_ok=True)
    out = LUA_DIR / f"{sid.lower()}.lua"
    out.write_text(render(sid), encoding="utf-8", newline="\n")
    return out


def main(argv=None) -> int:
    ids = [a.upper() for a in (argv if argv is not None else sys.argv[1:])] or sorted(specs.SPECS)
    for sid in ids:
        if sid not in specs.SPECS:
            print(f"unknown experiment {sid}; known: {sorted(specs.SPECS)}")
            return 2
        p = write(sid)
        print(f"{sid}: wrote {p.relative_to(HERE.parents[2])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
