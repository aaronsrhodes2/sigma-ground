# ── contrast: ask only the first quantity and the plan stops there ───────────────────
BY_ID = {r.id: r for r in RR.RECIPES}


def contrast(id, chain_id, templates, tool, args, distractors=(), per=60):
    """One call that answers only the chain's first quantity. The chain's slots are reused;
    `distractors` are quantities the question states that the call does not need."""
    base = BY_ID[chain_id]
    used = {x for kind, x in args.values() if kind == "s"}
    slots = {k: v for k, v in base.slots.items() if k in used or k in distractors}
    return RR.add(id, "contrast", slots, templates, [(tool, args)],
                  {1: base.bounds[1]} if 1 in base.bounds else {}, per, tuple(distractors))


