"""Scoreboard for the N-body shoot-out against JPL DE440: tables and a figure from merged results.

Reads rolling_shootout_<pass>.json files (scripts/run_shootout_parallel.py output), computes for each (predictor, body) the
MEDIAN over windows of the position error at the +N yr samples, and writes:
  * Table 1  headline bodies (planets, Moon, the slower moons) at +1 and +5 yr, every predictor;
  * Table 2  the integrator-limited moons (their phase is lost to integrator round-off; reported separately, never averaged in);
  * Table 3  what each force layer buys: median over planets and the Moon of (ablation error / headline error);
  * the same headline row from a BEFORE file (the old tracked fixture), when given, for the before/after proof.
Errors are heliocentric position errors in km (the rolling shoot-out stores AU; 1 AU = 149,597,870.7 km, IAU 2012).

usage: python scripts/shootout_scoreboard.py RESULTS.json [RESULTS_long.json] [--before OLD.json --before-map jpl_de440=de440_stack]
                                              [--out-md misc/SHOOTOUT_SCOREBOARD.md] [--out-png fig.png]
"""
from __future__ import annotations

import argparse
import json
import math
import statistics
import sys
from collections import defaultdict
from pathlib import Path

AU_KM = 149_597_870.7
LIMITED = ("Phobos", "Deimos", "Mimas", "Enceladus", "Io", "Miranda")
PLANETS = ("Mercury", "Venus", "Earth", "Mars", "Jupiter", "Saturn", "Uranus", "Neptune", "Pluto")
ORDER = ["de440_stack", "de440_no_eih", "de440_no_zonals", "de440_no_tides", "de440_no_srp", "newton_same_dt", "kepler_forecast"]


def load(path: Path) -> dict:
    d = json.loads(Path(path).read_text())
    return d


def errors_at(samples: list[dict], years: float, tol_d: float = 3.0) -> dict[tuple[str, str], list[float]]:
    """(predictor, body) -> list of errors (km) at start + years, one per window."""
    out: dict[tuple[str, str], list[float]] = defaultdict(list)
    for s in samples:
        e = s.get("error_au")
        if e is None or (isinstance(e, float) and math.isnan(e)):
            continue
        dt = s["sample_jd"] - s["window_start_jd"]
        if abs(dt - years * 365.25) <= tol_d:
            out[(s["predictor"], s["body"])].append(e * AU_KM)
    return out


def med(xs: list[float]) -> float | None:
    return statistics.median(xs) if xs else None


def fmt(x: float | None) -> str:
    if x is None:
        return "–"
    if x >= 1e6:
        return f"{x:.2e}"
    if x >= 1000:
        return f"{x:,.0f}"
    if x >= 10:
        return f"{x:.1f}"
    return f"{x:.2f}"


def table(rows: list[str], preds: list[str], cell: dict, title: str) -> list[str]:
    L = [f"**{title}**", "", "| body | " + " | ".join(preds) + " |", "|---|" + "---|" * len(preds)]
    for b in rows:
        L.append(f"| {b} | " + " | ".join(fmt(cell.get((p, b))) for p in preds) + " |")
    return L + [""]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("results", type=Path, nargs="+")
    ap.add_argument("--before", type=Path, default=None)
    ap.add_argument("--before-map", nargs="*", default=["jpl_de440=de440_stack", "pure_newton=newton_same_dt", "kepler=kepler_forecast"])
    ap.add_argument("--out-md", type=Path, default=Path("misc/SHOOTOUT_SCOREBOARD.md"))
    ap.add_argument("--out-png", type=Path, default=None)
    ap.add_argument("--out-json", type=Path, default=None)
    a = ap.parse_args()

    samples, meta = [], []
    for r in a.results:
        d = load(r)
        samples += d["samples"]
        meta.append(d["metadata"])
    # a window can appear in two passes (the short and the long pass share j2005 and j2006): count each (predictor, body, window, epoch) once
    seen, uniq = set(), []
    for s_ in samples:
        k_ = (s_["predictor"], s_["body"], s_["window_start_jd"], s_["sample_jd"])
        if k_ not in seen:
            seen.add(k_)
            uniq.append(s_)
    samples = uniq
    preds = [p for p in ORDER if any(s["predictor"] == p for s in samples)]
    extra = sorted({s["predictor"] for s in samples} - set(preds))
    preds += extra
    bodies = sorted({s["body"] for s in samples})
    horizons = {1.0: errors_at(samples, 1.0), 5.0: errors_at(samples, 5.0)}
    if any(m.get("prediction_horizon_yr", 0) >= 20 for m in meta):
        horizons[20.0] = errors_at(samples, 20.0)

    head_bodies = [b for b in PLANETS if b in bodies] + (["Moon"] if "Moon" in bodies else []) + \
        sorted(b for b in bodies if b not in PLANETS and b != "Moon" and b not in LIMITED and b != "Sun")
    lim_bodies = [b for b in LIMITED if b in bodies]
    md = ["# N-body shoot-out against JPL DE440: scoreboard", "",
          f"Generated by `scripts/shootout_scoreboard.py`. Windows: {sorted({k for m in meta for k in m.get('window_start_keys', [])})}. "
          f"Predictors: {', '.join(preds)}. Step (canonical set): {sorted({m.get('dt_days') for m in meta if m.get('dt_days')})} d. "
          "Each cell is the **median over windows** of the heliocentric position error (km) at that horizon.", ""]
    summary: dict = {"cells": {}}
    wins = {p: {s_["window_start_jd"] for s_ in samples if s_["predictor"] == p} for p in preds}
    md += ["**Windows per predictor:** " + ", ".join(f"{p} {len(w)}" for p, w in wins.items()) +
           ". Columns with fewer windows are medians over a thinner set, so compare columns only on the common windows (Table 3 does)", ""]
    for yrs, E in horizons.items():
        cell = {k: med(v) for k, v in E.items()}
        summary["cells"][f"{yrs:g}yr"] = {f"{p}|{b}": v for (p, b), v in cell.items()}
        md += table(head_bodies, preds, cell, f"Table 1 — headline bodies at +{yrs:g} yr (km)")
        md += table(lim_bodies, preds, cell, f"Table 2 — integrator-limited moons at +{yrs:g} yr (km; phase lost to round-off, not averaged into anything)")
    # layer contributions
    key_bodies = [b for b in PLANETS[:5] + ("Moon",) if b in bodies]
    common = set.intersection(*wins.values()) if wins else set()
    cell5 = {k: med(v) for k, v in errors_at([s_ for s_ in samples if s_["window_start_jd"] in common], 5.0).items()}
    md += [f"**Table 3 — what each layer buys** (median over Mercury–Jupiter and the Moon of ablation error ÷ headline error at +5 yr, "
           f"on the {len(common)} windows common to every predictor; >1 means the layer helps)", "", "| predictor | median ratio | per body |", "|---|---|---|"]
    for p in preds:
        if p == "de440_stack":
            continue
        rat = {b: cell5[(p, b)] / cell5[("de440_stack", b)] for b in key_bodies
               if cell5.get((p, b)) and cell5.get(("de440_stack", b))}
        if rat:
            md.append(f"| {p} | {statistics.median(rat.values()):.2f} | " + ", ".join(f"{b} {v:.2f}" for b, v in rat.items()) + " |")
    md.append("")
    # before / after: same windows, same horizon, old predictor -> new predictor
    if a.before:
        old = load(a.before)
        old_windows = set(old["metadata"].get("window_start_keys", []))
        old_jds = {s_["window_start_jd"] for s_ in old["samples"]}
        yrs_old = next((y for y in (3.0, 2.0, 1.0) if any(abs(s_["sample_jd"] - s_["window_start_jd"] - y * 365.25) < 3 for s_ in old["samples"])), 1.0)
        oldE = errors_at(old["samples"], yrs_old)
        newE = errors_at([s_ for s_ in samples if s_["window_start_jd"] in old_jds], yrs_old)
        pairs = [x.split("=") for x in a.before_map]
        md += [f"**Table 4 — before / after** (old tracked fixture, window(s) {sorted(old_windows)}, +{yrs_old:g} yr, median km; "
               f"new run restricted to the same window(s). Old → new: {', '.join(f'{o} → {n}' for o, n in pairs)})", "",
               "| predictor pair | body | old | new | old ÷ new |", "|---|---|---|---|---|"]
        for oldname, newname in pairs:
            for b in head_bodies + lim_bodies:
                o, n = med(oldE.get((oldname, b), [])), med(newE.get((newname, b), []))
                if o and n:
                    md.append(f"| {oldname} → {newname} | {b} | {fmt(o)} | {fmt(n)} | {o / n:.1f}× |")
        md.append("")
    a.out_md.parent.mkdir(parents=True, exist_ok=True)
    a.out_md.write_text("\n".join(md) + "\n", encoding="utf-8")
    if a.out_json:
        a.out_json.write_text(json.dumps(summary))
    print("wrote", a.out_md)
    if a.out_png:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        import numpy as np
        show = [b for b in PLANETS[:5] + ("Moon",) if b in bodies]
        fig, ax = plt.subplots(figsize=(11, 5.5), dpi=170)
        cols = {"de440_stack": "#2a78d6", "de440_no_eih": "#eb6834", "de440_no_zonals": "#1baf7a", "de440_no_tides": "#8b5cf6",
                "de440_no_srp": "#52514e", "newton_same_dt": "#b22222", "kepler_forecast": "#898781"}
        w = 0.8 / max(1, len(preds))
        for i, p in enumerate(preds):
            ys = [cell5.get((p, b)) or np.nan for b in show]
            ax.bar(np.arange(len(show)) + i * w, ys, w, label=p, color=cols.get(p, "#999999"))
        ax.set_yscale("log"); ax.set_xticks(np.arange(len(show)) + 0.4 - w / 2); ax.set_xticklabels(show)
        ax.set_ylabel("median position error at +5 yr (km)"); ax.grid(axis="y", color="#e1e0d9", lw=0.6)
        ax.set_title("N-body shoot-out vs JPL DE440 (median over windows): each force layer against the headline stack")
        ax.legend(frameon=False, fontsize=8, ncol=2)
        fig.tight_layout(); a.out_png.parent.mkdir(parents=True, exist_ok=True); fig.savefig(a.out_png)
        print("wrote", a.out_png)
    return 0


if __name__ == "__main__":
    sys.exit(main())
